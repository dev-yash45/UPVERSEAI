"use strict";

const planningSteps = [
    { icon: "🧠", text: "Analyzing your travel preferences & style...", progress: 15 },
    { icon: "📍", text: "Surveying destination heritage & routes...", progress: 35 },
    { icon: "🏨", text: "Selecting verified stays & budget breakdown...", progress: 60 },
    { icon: "🍽️", text: "Pairing authentic cuisine & street food spots...", progress: 80 },
    { icon: "✨", text: "Curating hidden gems & final itinerary...", progress: 100 }
];

let planningInterval = null;

/* ==========================================================
   PLANNING UI ANIMATION
========================================================== */
function showPlanningUI() {
    const panel = document.getElementById("tripAISection");
    if (!panel) return;
    panel.classList.remove("hidden");
    panel.style.display = "block";
    panel.scrollIntoView({ behavior: "smooth", block: "center" });
}

function hidePlanningUI() {
    const panel = document.getElementById("tripAISection");
    if (panel) {
        panel.classList.add("hidden");
        panel.style.display = "none";
    }
}

function startPlanningAnimation() {
    const fill = document.getElementById("tripProgressFill");
    const percent = document.getElementById("tripProgressPercent");
    const message = document.getElementById("tripPlanningMessage");
    const stepBox = document.getElementById("tripPlanningSteps");

    if (fill) fill.style.width = "0%";
    if (percent) percent.textContent = "0%";
    if (message) message.textContent = "Initializing UPVERSE AI...";
    if (stepBox) stepBox.innerHTML = "";

    let current = 0;
    if (planningInterval) clearInterval(planningInterval);

    planningInterval = setInterval(() => {
        if (current >= planningSteps.length) {
            clearInterval(planningInterval);
            return;
        }

        const step = planningSteps[current];
        if (fill) fill.style.width = `${step.progress}%`;
        if (percent) percent.textContent = `${step.progress}%`;
        if (message) message.textContent = step.text;

        if (stepBox) {
            const div = document.createElement("div");
            div.className = "planning-step completed";
            div.innerHTML = `<span>${step.icon}</span> <span>${step.text}</span>`;
            stepBox.appendChild(div);
        }

        current++;
    }, 450);
}

function completePlanningAnimation() {
    if (planningInterval) clearInterval(planningInterval);
    const fill = document.getElementById("tripProgressFill");
    const percent = document.getElementById("tripProgressPercent");
    const message = document.getElementById("tripPlanningMessage");

    if (fill) fill.style.width = "100%";
    if (percent) percent.textContent = "100%";
    if (message) message.textContent = "Itinerary Generated Successfully! ✨";
}

function scrollToResults() {
    const result = document.getElementById("tripResult");
    if (result) {
        result.scrollIntoView({ behavior: "smooth", block: "start" });
    }
}

